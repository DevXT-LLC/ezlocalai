void expect(bool value, const std::string &message) { if (!value) throw std::runtime_error(message); }
std::string read_file(const std::string &path) {
    std::ifstream input(path, std::ios::binary);
    expect(bool(input), "could not read " + path);
    return {std::istreambuf_iterator<char>(input), std::istreambuf_iterator<char>()};
}
std::vector<std::string> split(const std::string &value, char separator) {
    std::vector<std::string> parts;
    size_t begin = 0;
    do {
        const auto end = value.find(separator, begin);
        parts.push_back(value.substr(begin, end == std::string::npos ? end : end - begin));
        if (end == std::string::npos) break;
        begin = end + 1;
    } while (true);
    return parts;
}
std::string unhex(const std::string &value) {
    expect(value.size() % 2 == 0, "invalid hex fixture");
    std::string result;
    for (size_t i = 0; i < value.size(); i += 2) result += static_cast<char>(std::stoi(value.substr(i, 2), nullptr, 16));
    return result;
}
std::string sha256(const std::string &value) {
    unsigned char digest[SHA256_DIGEST_LENGTH];
    SHA256(reinterpret_cast<const unsigned char *>(value.data()), value.size(), digest);
    std::ostringstream result;
    for (const auto byte : digest) result << std::hex << std::setw(2) << std::setfill('0') << unsigned(byte);
    return result.str();
}

// Keep field order, strings, types and integer precision. Normalize equivalent
// float spelling and the timestamp generated by the API.
std::string stable_json(const std::string &input) {
    if (input == "Internal Server Error") return input;
    std::string result, key;
    for (size_t i = 0; i < input.size();) {
        const char ch = input[i];
        if (std::isspace(static_cast<unsigned char>(ch))) { ++i; continue; }
        if (ch == '"') {
            const auto begin = i++;
            while (i < input.size() && input[i] != '"') {
                if (input[i] == '\\') ++i;
                ++i;
            }
            expect(i < input.size(), "unterminated JSON string");
            ++i;
            const auto value = input.substr(begin, i - begin);
            result += value;
            auto next = input.find_first_not_of(" \t\r\n", i);
            key = next != std::string::npos && input[next] == ':' ? value : "";
        } else if (ch == '-' || (ch >= '0' && ch <= '9')) {
            const auto begin = i++;
            while (i < input.size() && std::string("0123456789.eE+-").find(input[i]) != std::string::npos) ++i;
            if (key == "\"created\"") result += '0';
            else if (input.substr(begin, i - begin).find_first_of(".eE") == std::string::npos) result += input.substr(begin, i - begin);
            else {
                std::ostringstream number;
                number << std::setprecision(17) << std::stod(input.substr(begin, i - begin));
                result += number.str();
            }
            key.clear();
        } else { result += ch; ++i; }
    }
    return result;
}

struct Exchange { std::string method, path, request, content_type, body; int status; std::string authorization; };
class ScriptedServer {
public:
    explicit ScriptedServer(std::vector<Exchange> script) : script_(std::move(script)) {
        fd_ = socket(AF_INET, SOCK_STREAM, 0);
        expect(fd_ >= 0, "upstream socket");
        sockaddr_in address{};
        address.sin_family = AF_INET;
        address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
        expect(bind(fd_, reinterpret_cast<sockaddr *>(&address), sizeof(address)) == 0, "bind upstream");
        socklen_t size = sizeof(address);
        expect(getsockname(fd_, reinterpret_cast<sockaddr *>(&address), &size) == 0, "upstream port");
        url = "http://127.0.0.1:" + std::to_string(ntohs(address.sin_port));
        expect(listen(fd_, 8) == 0, "listen upstream");
        thread_ = std::thread([this] { serve(); });
    }
    ~ScriptedServer() { finish(); }
    void finish() {
        if (fd_ < 0) return;
        stopped_ = true;
        shutdown(fd_, SHUT_RDWR);
        if (thread_.joinable()) thread_.join();
        close(fd_); fd_ = -1;
    }
    void verify(const std::string &name) {
        finish();
        expect(error_.empty(), name + ": " + error_);
        expect(index_ == script_.size(), name + ": expected " + std::to_string(script_.size()) + " upstream requests, saw " + std::to_string(index_));
    }
    std::string url;
private:
    void serve() {
        try {
            while (!stopped_) {
                pollfd descriptor{fd_, POLLIN, 0};
                if (poll(&descriptor, 1, 100) <= 0) continue;
                const int peer = accept(fd_, nullptr, nullptr);
                if (peer < 0) continue;
                timeval timeout{3, 0};
                setsockopt(peer, SOL_SOCKET, SO_RCVTIMEO, &timeout, sizeof(timeout));
                std::string raw;
                char buffer[4096];
                size_t expected = std::string::npos, header_end = std::string::npos;
                while (expected == std::string::npos || raw.size() < expected) {
                    const auto n = recv(peer, buffer, sizeof(buffer), 0);
                    if (n <= 0) break;
                    raw.append(buffer, static_cast<size_t>(n));
                    header_end = raw.find("\r\n\r\n");
                    const auto length = raw.find("Content-Length: ");
                    if (header_end != std::string::npos) expected = header_end + 4 + (length == std::string::npos ? 0 : std::stoul(raw.substr(length + 16)));
                }
                std::istringstream line(raw);
                std::string method, path;
                line >> method >> path;
                Exchange exchange{"", "", "", "text/plain", "unexpected upstream request", 500};
                if (index_ >= script_.size()) error_ = "unexpected " + method + " " + path;
                else {
                    exchange = script_[index_++];
                    const auto body = header_end == std::string::npos ? "" : raw.substr(header_end + 4);
                    if (method != exchange.method || path != exchange.path) error_ = "request " + method + " " + path + " expected " + exchange.method + " " + exchange.path;
                    if (stable_json(body) != stable_json(exchange.request)) error_ = "request body " + body + " expected " + exchange.request;
                    if (!exchange.authorization.empty() && raw.find("Authorization: " + exchange.authorization + "\r\n") == std::string::npos) error_ = "missing upstream authorization " + exchange.authorization;
                    if (exchange.authorization.empty() && raw.find("Authorization:") != std::string::npos) error_ = "unexpected upstream authorization";
                }
                const auto response = "HTTP/1.1 " + std::to_string(exchange.status) + " Response\r\nContent-Type: " + exchange.content_type + "\r\nContent-Length: " + std::to_string(exchange.body.size()) + "\r\nConnection: close\r\n\r\n" + exchange.body;
                size_t sent = 0;
                while (sent < response.size()) {
                    const auto n = send(peer, response.data() + sent, response.size() - sent, MSG_NOSIGNAL);
                    if (n <= 0) break;
                    sent += static_cast<size_t>(n);
                }
                shutdown(peer, SHUT_RDWR); close(peer);
            }
        } catch (const std::exception &e) { error_ = e.what(); }
    }
    int fd_ = -1;
    std::thread thread_;
    std::atomic<bool> stopped_{false};
    std::vector<Exchange> script_;
    size_t index_ = 0;
    std::string error_;
};

void environment() {
    for (const auto &entry : ezlocalai::environment_defaults) unsetenv(entry.first.data());
    setenv("EZLOCALAI_DOTENV_PATH", "", 1);
    setenv("ROUTER_DRAIN_FILE", "", 1);
    setenv("USAGE_FILE", "usage.json", 1);
    setenv("SDCPP_BIN", "/missing/sd-cli", 1);
}
size_t reference_cases(const std::filesystem::path &root, const std::filesystem::path &fixture) {
    size_t count = 0, failures = 0;
    std::istringstream lines(read_file(fixture.string()));
    for (std::string line; std::getline(lines, line);) {
        if (line.empty()) continue;
        if (line[0] == '#') {
            const auto marker = line.find(" sha256=");
            if (marker != std::string::npos) expect(sha256(read_file((root / line.substr(2, marker - 2)).string())) == line.substr(marker + 8), "Video API reference changed");
            continue;
        }
        ++count;
        const auto c = split(line, '\t'); expect(c.size() == 7, "video API fixture columns");
        try {
            environment();
            for (const auto &entry : split(c[1], ';')) {
                const auto equal = entry.find('='); setenv(entry.substr(0, equal).c_str(), unhex(entry.substr(equal + 1)).c_str(), 1);
            }
            std::vector<Exchange> script;
            for (const auto &step : split(unhex(c[6]), '\n')) {
                if (step.empty()) continue;
                const auto s = split(step, '\t'); expect(s.size() == 7, "video transcript columns");
                script.push_back({s[0], s[1], unhex(s[2]), unhex(s[4]), unhex(s[5]), std::stoi(s[3]), unhex(s[6])});
            }
            ScriptedServer upstream(std::move(script));
            for (const char *key : {"IMAGE_SERVER", "ROUTER_URL", "FALLBACK_SERVER"}) {
                const char *value = getenv(key);
                if (value && std::string(value) == "<UPSTREAM>") setenv(key, upstream.url.c_str(), 1);
            }
            ezl_env_config config{}; ezl_load_config(&config);
            ezlocalai::NativeServer server(config, std::make_unique<ezlocalai::EchoInferenceBackend>("model"));
            const auto response = server.handle_request("POST", "/v1/videos/generations", "Bearer " + std::string(config.api_key), unhex(c[2]), "application/json");
            upstream.verify(c[0]);
            expect(response.status == std::stoi(c[3]) && response.content_type == unhex(c[4]), c[0] + " status/type " + std::to_string(response.status) + " " + response.content_type + " expected " + c[3] + " " + unhex(c[4]));
            expect(stable_json(response.body) == stable_json(unhex(c[5])), c[0] + " response " + response.body + " expected " + unhex(c[5]));
        } catch (const std::exception &e) { if (++failures <= 30) std::cerr << c[0] << ": " << e.what() << '\n'; }
    }
    expect(failures == 0, std::to_string(failures) + " video API differential failures");
    expect(count == 398, "all video API cases"); return count;
}
void cache_cases() {
    const std::string payload = R"({"prompt":"","response_format":"url","size":"768x512","num_frames":121,"num_inference_steps":18,"guidance_scale":3.5,"frame_rate":24})";
    for (const std::string target : {"IMAGE_SERVER", "ROUTER_URL", "FALLBACK_SERVER"}) for (const bool available : {false, true}) {
        environment(); setenv("VIDEO_ENABLED", "false", 1); setenv("EZLOCALAI_API_KEY", "test-secret", 1);
        const auto path = target == "IMAGE_SERVER" ? "/v1/models" : target == "ROUTER_URL" ? "/v1/router/health" : "/v1/resources";
        std::vector<Exchange> script = {{"GET", path, "", "application/json", R"({"alive_workers":1,"free_vram_gb":64})", available ? 200 : 503, "Bearer test-secret"}};
        if (available) for (int i = 0; i < 2; ++i) script.push_back({"POST", "/v1/videos/generations", payload, "application/json", R"({"result":"ok"})", 200, "Bearer test-secret"});
        ScriptedServer upstream(std::move(script)); setenv(target.c_str(), upstream.url.c_str(), 1);
        ezl_env_config config{}; ezl_load_config(&config);
        ezlocalai::NativeServer server(config, std::make_unique<ezlocalai::EchoInferenceBackend>("model"));
        for (int i = 0; i < 2; ++i) {
            const auto response = server.handle_request("POST", "/v1/videos/generations", "Bearer test-secret", "{}");
            expect(response.status == 200 && (available ? response.body.find("ok") != std::string::npos : response.body.find("Video generation not available") != std::string::npos), target + " cached response");
        }
        upstream.verify(target + " caches positive and negative availability");
        const auto resources = server.handle_request("GET", "/v1/resources", "Bearer test-secret", "");
        expect(resources.body.find("\"video\":") == std::string::npos, "forwarding does not create local video residency or slots");
    }
}
