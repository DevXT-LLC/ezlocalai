int main(int argc, char **argv) {
    try {
        expect(argc == 3, "reference checkout and fixture required");
        const auto root = std::filesystem::absolute(argv[1]), fixture = std::filesystem::absolute(argv[2]);
        const auto previous = std::filesystem::current_path(); char directory[] = "/tmp/ezlocalai-video-api-XXXXXX";
        expect(mkdtemp(directory), "temporary directory"); std::filesystem::current_path(directory);
        const auto count = reference_cases(root, fixture);
        cache_cases();
        std::filesystem::current_path(previous); std::filesystem::remove_all(directory);
        std::cout << "Verified " << count << " reference video API cases over native HTTP\n"; return 0;
    } catch (const std::exception &e) { std::cerr << "FAIL: " << e.what() << '\n'; return 1; }
}
