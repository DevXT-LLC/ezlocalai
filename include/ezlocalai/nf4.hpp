inline float from_bf16(uint16_t value) {
    uint32_t bits = uint32_t(value) << 16;
    float result;
    std::memcpy(&result, &bits, sizeof(result));
    return result;
}
inline uint16_t to_bf16(float value) {
    uint32_t bits;
    std::memcpy(&bits, &value, sizeof(bits));
    return static_cast<uint16_t>((bits + 0x7fff + ((bits >> 16) & 1)) >> 16);
}
inline float from_f16(uint16_t value) {
    const uint32_t exponent = (value >> 10) & 31, mantissa = value & 1023;
    if (!exponent) {
        const float magnitude = std::ldexp(static_cast<float>(mantissa), -24);
        return value & 0x8000 ? -magnitude : magnitude;
    }
    const uint32_t bits = (uint32_t(value & 0x8000) << 16) |
        ((exponent == 31 ? 255 : exponent + 112) << 23) | (mantissa << 13);
    float result;
    std::memcpy(&result, &bits, sizeof(result));
    return result;
}
inline uint16_t to_f16(float value) {
    uint32_t bits;
    std::memcpy(&bits, &value, sizeof(bits));
    const uint16_t sign = (bits >> 16) & 0x8000;
    const uint32_t raw_exponent = (bits >> 23) & 255;
    uint32_t mantissa = bits & 0x7fffff;
    if (raw_exponent == 255) return sign | 0x7c00 | (mantissa ? 0x200 : 0);
    int exponent = static_cast<int>(raw_exponent) - 112;
    if (exponent >= 31) return sign | 0x7c00;
    if (exponent <= 0) {
        if (exponent < -10) return sign;
        mantissa |= 0x800000;
        const unsigned shift = 14 - exponent;
        return sign | ((mantissa + (1u << (shift - 1)) - 1 + ((mantissa >> shift) & 1)) >> shift);
    }
    mantissa += 0xfff + ((mantissa >> 13) & 1);
    if (mantissa & 0x800000) { ++exponent; mantissa = 0; }
    return sign | (exponent << 10) | (mantissa >> 13);
}
