// Portable block-64 NF4 representation, including optional nested block-256
// statistics. Scales retain the reconstructed float32 values for streaming
// dequantization. This helper does not choose a GPU or a model residency policy.
// Supply the selected CUDA device's driver attributes to reproduce its nested
// statistics reduction. Without them, the host sum can differ in its last bit.
struct Nf4CudaDevice {
    int multiprocessors;
    int max_threads_per_multiprocessor;
};

struct Nf4Weights {
    size_t count = 0;
    std::vector<uint8_t> packed;
    std::vector<float> scales;
    std::vector<uint8_t> nested;
    std::vector<float> nested_absmax;
    float offset = 0;
};

template<class Decode>
inline Nf4Weights quantize_nf4_16bit(const uint16_t* values, size_t count, bool nested,
                                  std::optional<Nf4CudaDevice> cuda_device, Decode decode) {
    using namespace nf4_detail;
    Nf4Weights result;
    result.count = count;
    if (!count) return result;
    if (!values) throw std::invalid_argument("NF4 input is null");
    result.packed.resize(count / 2 + count % 2);
    result.scales.resize(count / 64 + (count % 64 != 0));
    double total = 0;
    for (size_t block = 0; block < result.scales.size(); ++block) {
        const size_t begin = block * 64, end = begin + std::min(size_t(64), count - begin);
        float maximum = 0;
        for (size_t i = begin; i < end; ++i) {
            const float value = decode(values[i]);
            if (!std::isfinite(value)) throw std::invalid_argument("NF4 requires finite weights");
            maximum = std::max(maximum, std::abs(value));
        }
        result.scales[block] = maximum;
        total += maximum;
        // BNB's all-zero normalization produces NaNs, whose decision-tree code
        // is zero. Preserve that packed representation without dividing by zero.
        if (maximum == 0) continue;
        const float reciprocal = 1.f / maximum;
        for (size_t i = begin; i < end; i += 2) {
            const auto high = quantize_value(decode(values[i]) * reciprocal);
            const float low = i + 1 < end ? decode(values[i + 1]) : 0.f;
            result.packed[i / 2] = (high << 4) | quantize_value(low * reciprocal);
        }
    }
    if (nested) {
        // Both paths project a float32 sum by a float32 reciprocal. Geometry
        // selects the CUDA addition order; otherwise use the host accumulator.
        result.offset = cuda_device
            ? pytorch_cuda_mean(result.scales, cuda_device->multiprocessors, cuda_device->max_threads_per_multiprocessor)
            : static_cast<float>(total) * (1.f / result.scales.size());
        result.nested.resize(result.scales.size());
        result.nested_absmax.resize(result.scales.size() / 256 + (result.scales.size() % 256 != 0));
        for (float& scale : result.scales) scale -= result.offset;
        for (size_t block = 0; block < result.nested_absmax.size(); ++block) {
            const size_t begin = block * 256, end = std::min(begin + 256, result.scales.size());
            float maximum = 0;
            for (size_t i = begin; i < end; ++i) maximum = std::max(maximum, std::abs(result.scales[i]));
            result.nested_absmax[block] = maximum;
            if (maximum == 0) continue;
            const float reciprocal = 1.f / maximum;
            for (size_t i = begin; i < end; ++i)
                result.nested[i] = dQuantize<0>(dynamic_code.data(), 0.f, result.scales[i] * reciprocal);
        }
        for (size_t i = 0; i < result.scales.size(); ++i) {
            // Keep the two operations separate, as in BNB's dequantize + offset.
            const volatile float centered = dynamic_code[result.nested[i]] * result.nested_absmax[i / 256];
            result.scales[i] = centered + result.offset;
        }
    }
    return result;
}

template<class Encode>
inline void dequantize_nf4_16bit(const Nf4Weights& weights, uint16_t* output, Encode encode) {
    using namespace nf4_detail;
    if (weights.packed.size() != weights.count / 2 + weights.count % 2 ||
        weights.scales.size() != weights.count / 64 + (weights.count % 64 != 0) ||
        (weights.count && !output)) throw std::invalid_argument("Invalid NF4 buffer");
    for (size_t i = 0; i < weights.count; ++i) {
        const auto code = (weights.packed[i / 2] >> (i % 2 ? 0 : 4)) & 15;
        output[i] = encode(nf4_dequantization_lut[code] * weights.scales[i / 64]);
    }
}
inline Nf4Weights quantize_nf4_bf16(const uint16_t* values, size_t count, bool nested = true,
                                  std::optional<Nf4CudaDevice> device = std::nullopt) {
    return quantize_nf4_16bit(values, count, nested, device, nf4_detail::from_bf16);
}
inline Nf4Weights quantize_nf4_f16(const uint16_t* values, size_t count, bool nested = true,
                                 std::optional<Nf4CudaDevice> device = std::nullopt) {
    return quantize_nf4_16bit(values, count, nested, device, nf4_detail::from_f16);
}
inline void dequantize_nf4_bf16(const Nf4Weights& weights, uint16_t* output) {
    dequantize_nf4_16bit(weights, output, nf4_detail::to_bf16);
}
inline void dequantize_nf4_f16(const Nf4Weights& weights, uint16_t* output) {
    dequantize_nf4_16bit(weights, output, nf4_detail::to_f16);
}
